"""Shared helpers for race profile scripts (see data/elections/2026/profiles/README.md)."""
import json
import re
from pathlib import Path

from render import render_markdown

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "data" / "elections" / "2026" / "profiles"
REVIEW = Path(__file__).resolve().parent / "review"
KEY = re.compile(r"\{([a-z0-9_]+)\}")


def _number(obj, sources, order):
    if isinstance(obj, str):
        def sub(m):
            key = m.group(1)
            if key not in sources:
                raise KeyError(f"unknown source {key}")
            if key not in order:
                order.append(key)
            return f"[{order.index(key) + 1}]"
        out = re.sub(r"\{([a-z0-9_]+)\}", sub, obj)
        return re.sub(r"\]\s*\[", ", ", re.sub(r"\s+(\[\d)", r" \1", out)).replace(" .", ".")
    if isinstance(obj, list):
        return [_number(x, sources, order) for x in obj]
    if isinstance(obj, dict):
        return {k: _number(v, sources, order) for k, v in obj.items()}
    return obj


def split_flags(profile, sources):
    """Pull review_flags out of a profile; resolve their citations."""
    flags = profile.pop("review_flags", None) or []
    used = set(KEY.findall(json.dumps(profile)))
    out = []
    for f in flags:
        keys = KEY.findall(f.get("summary", ""))
        for k in keys:
            if k not in sources:
                raise KeyError(f"unknown source {k} in review_flags")
        out.append({**f, "summary": KEY.sub("", f.get("summary", "")).replace(" .", ".").strip(),
                    "sources": [{"title": sources[k][0], "publisher": sources[k][1],
                                 "date": sources[k][2], "url": sources[k][3]}
                                for k in dict.fromkeys(keys)]})
    # sources cited only by flags stay out of the public profile
    sources = {k: v for k, v in sources.items()
               if k in used or not any(k in KEY.findall(f.get("summary", "")) for f in flags)}
    return out, sources


def write_review(race_id, title, flags):
    path = REVIEW / f"{race_id}.json"
    if not flags:
        path.unlink(missing_ok=True)
        return
    REVIEW.mkdir(exist_ok=True)
    path.write_text(json.dumps({"race_id": race_id, "office": title, "flags": flags},
                               indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


def write_review_index():
    items = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(REVIEW.glob("*.json"))]
    lines = ["# Review flags\n\n",
             "Sensitive items held for a second, careful editorial pass (criminal cases, "
             "misconduct allegations, firings, censures). \"held\" items are not on the "
             "public profile; \"in profile\" items are, and need a second look. "
             "Generated by build_from_src.py from each source file's review_flags.\n"]
    for r in items:
        lines.append(f"\n## {r['office']} (`{r['race_id']}`)\n")
        for f in r["flags"]:
            lines.append(f"\n- **{f['person']}** — {f['category']} — _{f['status']}_\n"
                         f"  {f['summary']}\n")
            if f.get("note"):
                lines.append(f"  Note: {f['note']}\n")
            for s in f["sources"]:
                lines.append(f"  - [{s['title']}]({s['url']}) — {s['publisher']}, {s['date']}\n")
    REVIEW.mkdir(exist_ok=True)
    (REVIEW / "REVIEW_FLAGS.md").write_text("".join(lines), encoding="utf-8")


def build_profile(profile, sources):
    """Number {key} citations, attach the source list, write .json and .md.
    review_flags are kept off the public profile (see split_flags)."""
    profile = dict(profile)
    flags, sources = split_flags(profile, sources)
    write_review(profile["race_id"], profile["office"]["title"], flags)
    write_review_index()
    order = []
    out = _number(profile, sources, order)
    out["sources"] = [
        {"id": i + 1, "title": sources[k][0], "publisher": sources[k][1],
         "date": sources[k][2], "url": sources[k][3]}
        for i, k in enumerate(order)
    ]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{out['race_id']}.json").write_text(
        json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    (OUT / f"{out['race_id']}.md").write_text(render_markdown(out), encoding="utf-8")
    unused = sorted(set(sources) - set(order))
    print(f"{out['race_id']}: {len(out['candidates'])} candidates, "
          f"{len(order)} sources; unused: {unused}")
    return out
